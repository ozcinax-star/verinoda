def _marks(fn):
    for m in experiment:
        fn = m(fn)
    return fn


@_marks
def test_pinned_file_passes_on_the_current_tree_and_backs_an_experiment_verified_claim(orders):
    repo, st, res = orders
    assert res["status"] == "pinned", res
    assert res["generated"] == "tests/pinned/test_pin_orders_pricing__apply_discount.py" and res["written"] is True
    assert res["selection"]["static"] >= 4 and "tests/test_pricing.py::test_compute_total" in res["tests"]
    assert res["cases"] == {"recorded": 4, "kept": 4, "dropped": {}}
    assert res["skipped_calls"] == {} and res["calls"] == 4
    assert res["replay_run"] == res["run_id"] and "confirm_run" not in res
    text = (repo / res["generated"]).read_text(encoding="utf-8")
    head = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True,
                          stdin=subprocess.DEVNULL).stdout.strip()
    assert text.startswith(f"# Generated by verinoda pin at commit {head[:12]} ")
    assert "tests/test_pricing.py::test_discount_applies_above_threshold" in text.split("import", 1)[0]
    assert "orders.pricing.apply_discount(200.0)" in text and "_pin_expected = 180.0" in text
    assert text.count("\ndef test_apply_discount_pin_") == 4 and "\r" not in text
    ast.parse(text)
    # the replay that backs the claim ran exactly this file on a copy of the working tree
    exp = st.get("experiments", res["run_id"])
    assert exp["status"] == "pass" and exp["environment"]["source"]["added"] == [res["generated"]]
    assert res["claim"]["status"] == "experiment_verified"
    assert "behaviour on these 4 inputs is pinned at commit" in res["claim"]["text"]
    # and it passes again when run like any other test file
    assert _run_file(repo, res["generated"])["outcome"] == "pass"


@_marks
def test_pinned_file_fails_after_a_deliberate_behaviour_change(orders, tmp_path):
    repo, st, res = orders
    assert res["written"]
    copy = tmp_path / "changed"
