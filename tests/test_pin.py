# -- the value encoder (in-process: the plugin module is inert when imported by Verinoda) ---------

@pytest.mark.parametrize("value", [
    None, True, 3, -0.5, float("inf"), "a'b\n", b"\x00x", (1,), [1, (2.0, "x")], {"k": [1, {2}]},
    {3, 1, 2}, frozenset({"b", "a"}), set(), frozenset(), decimal.Decimal("1.10"), fractions.Fraction(1, 3),
    datetime.date(2024, 2, 29), datetime.datetime(2024, 1, 1, 12, 0, tzinfo=datetime.timezone.utc),
    datetime.timedelta(days=2, seconds=5), float("nan"),
])
def test_supported_values_rebuild_to_equal_values_of_the_same_type(value):
    imports: set = set()
    src = plug.value_source(value, imports)
    assert plug.same(plug.rebuild(src, imports), value)


def test_set_sources_do_not_depend_on_iteration_order():
    assert plug.value_source({"b", "a", "c"}, set()) == "{'a', 'b', 'c'}"


@pytest.mark.parametrize("value, reason", [
    (object(), "unsupported type builtins.object"),
    (complex(1, 2), "unsupported type builtins.complex"),
    (datetime.datetime(2024, 1, 1, tzinfo=datetime.timezone(datetime.timedelta(hours=3))), None),
    ([1, object()], "unsupported type builtins.object"),
    ("x" * (plug.MAX_LEN + 1), "str longer than"),
])
def test_other_values_are_skipped_with_a_reason(value, reason):
    if reason is None:  # a fixed-offset timezone is a datetime.timezone: supported
        assert plug.value_source(value, set())
        return
    with pytest.raises(plug._Skip, match=reason):
        plug.value_source(value, set())


def test_same_compares_types_all_the_way_down():
    assert not plug.same(1, 1.0) and not plug.same([1], [True]) and not plug.same((1,), [1])
    assert plug.same({"a": [float("nan")]}, {"a": [float("nan")]})


def test_exceptions_are_named_by_an_importable_type_and_their_message():
    imports: set = set()
    assert plug.exception_source(ValueError("bad"), imports) == ("ValueError", "bad") and imports == set()
    assert plug.exception_source(decimal.InvalidOperation("x"), imports)[0] == "decimal.InvalidOperation"
    with pytest.raises(plug._Skip, match="memory address"):
        plug.exception_source(RuntimeError("<object at 0x0000>"), set())
    with pytest.raises(plug._Skip, match="not an Exception"):
        plug.exception_source(KeyboardInterrupt(), set())
