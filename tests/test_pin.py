def test_instance_methods_of_other_classes_and_generators_are_unsupported_without_a_run(tmp_path):
    _write(tmp_path, {**TOY, "toy/gen.py": "def items(n):\n    yield from range(n)\n"})
    st = open_store(tmp_path, create=True)
    try:
        plain = pin.pin(st, tmp_path, "toy/core.py::Plain.get")
        gen = pin.pin(st, tmp_path, "toy/gen.py::items")
        test_code = pin.pin(st, tmp_path, "tests/test_core.py::test_price")
    finally:
        st.close()
    assert plain["status"] == "unsupported" and "not a dataclass" in plain["headline"]
    assert gen["status"] == "unsupported" and "generator" in gen["headline"]
    assert test_code["status"] == "unsupported" and "test code" in test_code["headline"]
    assert "record_run" not in plain and "record_run" not in gen


