def _case(**kw):
    c = {"call": {"self": None, "args": ["1"], "kwargs": []}, "imports": [], "outs": [{"r": "1"}]}
    for k, v in kw.items():
        if k in ("args", "kwargs", "self"):
            c["call"][k] = v
        else:
            c[k] = v
    return c


