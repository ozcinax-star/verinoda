def _git(cwd: Path, *args: str) -> None:
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", "-c", "core.autocrlf=false", *args],
                   cwd=cwd, check=True, capture_output=True, stdin=subprocess.DEVNULL)


def _commit(repo: Path) -> None:
    _git(repo, "init", "-q")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "init")


def _write(root: Path, files: dict[str, str]) -> None:
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))


def _run_file(repo: Path, rel: str) -> dict:
    st = open_store(repo, create=True)
    try:
        return experiments.run(st, repo, [experiments.python_for(repo), "-m", "pytest", "-q", rel],
                               hypothesis=f"the pinned tests in {rel} pass")
    finally:
        st.close()


