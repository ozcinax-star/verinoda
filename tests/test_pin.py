"""``verinoda pin``: a function's behaviour recorded while its tests run, written as a pytest file that passes.

Real child processes throughout (the experiment runner's throw-away copies). The orders_app copy is selected
through the index (static reach); the toy project names its tests. The generated file must pass on the current
tree, fail after a deliberate behaviour change in a copy, and leave out what does not replay the same.
"""

from __future__ import annotations

import os

os.environ.setdefault("GRAPHIFY_OUT", ".verinoda/index")

import ast  # noqa: E402
