def _dump(rows: list[dict]) -> str:
    return json.dumps(rows, indent=1, ensure_ascii=False) + "\n"


def build() -> dict:
    ids = [c[0] for c in CASES]
    assert len(ids) == len(set(ids)), "duplicate case id"
    rows = [{"id": i, "repo": r, "question": q, "answer": a, "at": at, "shape": s} for i, r, q, a, at, s in CASES]
    text = _dump(rows)
    (HERE / "held_out.json").write_text(text, encoding="utf-8", newline="\n")
    orders = ROOT / "examples" / "orders_app"
    examples = {p.relative_to(ROOT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                for p in sorted(orders.rglob("*")) if p.is_file() and "__pycache__" not in p.parts
                and ".verinoda" not in p.parts}
    manifest = {"written": WRITTEN,
                "note": "sha256 of the held-out set as frozen before verinoda tq was run on any of its questions",
                "files": {"held_out.json": hashlib.sha256(text.encode("utf-8")).hexdigest()},
                "repos": REPOS, "examples": examples,
                "counts": {"held_out.json": len(rows)}}
    (HERE / "MANIFEST.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8", newline="\n")
    return manifest


